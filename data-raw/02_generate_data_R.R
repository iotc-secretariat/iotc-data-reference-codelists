# ----------------------------------------------------------------------
# Read catalogue metadata
# ----------------------------------------------------------------------

catalogue <- as.data.table(
  dbGetQuery(
    C_REFERENCE_DATA,
    "
    SELECT
        source_schema,
        source_relation,
        cl_name,
        anchor,
        description_en
    FROM refs_meta.codelists_catalogue
    "
  )
)

# ----------------------------------------------------------------------
# Read actual objects contained in data/*.rda
# ----------------------------------------------------------------------

rda_files <- list.files(
  "data",
  pattern = "\\.rda$",
  full.names = TRUE
)

package_data <- rbindlist(
  lapply(
    rda_files,
    function(f) {
      
      e <- new.env(parent = emptyenv())
      object_names <- load(f, envir = e)
      
      rbindlist(
        lapply(
          object_names,
          function(nm) {
            
            x <- get(nm, envir = e)
            
            data.table(
              package_name = nm,
              rda_file = basename(f),
              columns = list(names(x))
            )
          }
        )
      )
    }
  )
)

setorder(package_data, package_name)

# ----------------------------------------------------------------------
# Exceptions where package name != catalogue cl_name
# Add other exceptions here if needed
# ----------------------------------------------------------------------

overrides <- c(
  CONDITIONS          = "INDIVIDUAL_CONDITIONS",
  DATA_COVERAGE_TYPES = "COVERAGE_TYPES",
  SPECIES             = "ALL_SPECIES"
)

package_data[
  ,
  cl_name := fifelse(
    package_name %in% names(overrides),
    unname(overrides[package_name]),
    package_name
  )
]

# ----------------------------------------------------------------------
# Join package objects with catalogue
# ----------------------------------------------------------------------

doc <- merge(
  package_data,
  catalogue,
  by = "cl_name",
  all.x = TRUE,
  sort = FALSE
)

setorder(doc, package_name)

# ----------------------------------------------------------------------
# Catalogue domain URLs
# ----------------------------------------------------------------------

domains <- c(
  refs_admin           = "admin",
  refs_biology         = "biological",
  refs_data            = "data",
  refs_fishery         = "fisheries",
  refs_fishery_config  = "fisheries",
  refs_gis             = "gis",
  refs_legacy          = "legacy",
  refs_socio_economics = "economics"
)

doc[
  ,
  domain := unname(domains[source_schema])
]

doc[
  ,
  source_url := fifelse(
    !is.na(domain) & !is.na(anchor),
    paste0(
      "https://data.iotc.org/reference/latest/domain/",
      domain,
      "/#",
      anchor
    ),
    "https://data.iotc.org/reference/latest"
  )
]

# ----------------------------------------------------------------------
# Report unmatched objects
# ----------------------------------------------------------------------

unmatched <- doc[
  is.na(description_en),
  .(package_name, cl_name, rda_file)
]

if (nrow(unmatched)) {
  message("\nObjects without catalogue description:\n")
  print(unmatched)
}

# ----------------------------------------------------------------------
# Roxygen helpers
# ----------------------------------------------------------------------

rox_wrap <- function(x, width = 76) {
  
  if (is.na(x) || !nzchar(trimws(x))) {
    return("#' IOTC reference code list.")
  }
  
  x <- gsub("[\r\n\t]+", " ", x)
  x <- gsub(" {2,}", " ", x)
  
  paste0(
    "#' ",
    strwrap(
      trimws(x),
      width = width - 3
    )
  )
}


make_block <- function(name, description, columns, source_url) {
  
  column_text <- paste(
    paste0("`", columns, "`"),
    collapse = ", "
  )
  
  c(
    paste0("#' ", name),
    "#'",
    rox_wrap(description),
    "#'",
    "#' @format A data frame containing the following columns:",
    rox_wrap(column_text),
    "#'",
    paste0("#' @source <", source_url, ">"),
    paste0('"', name, '"'),
    ""
  )
}

# ----------------------------------------------------------------------
# Generate documentation blocks
# ----------------------------------------------------------------------

blocks <- Map(
  make_block,
  name        = doc$package_name,
  description = doc$description_en,
  columns     = doc$columns,
  source_url  = doc$source_url
)

header <- c(
  "# ----------------------------------------------------------------------",
  "# AUTO-GENERATED FILE - DO NOT EDIT MANUALLY",
  "# Generated by data-raw/generate_data_R.R",
  "# ----------------------------------------------------------------------",
  ""
)

writeLines(
  c(
    header,
    unlist(blocks, use.names = FALSE)
  ),
  "R/data.R"
)

dbDisconnect(C_REFERENCE_DATA)

message(
  "\nGenerated R/data.R with ",
  nrow(doc),
  " documentation entries."
)